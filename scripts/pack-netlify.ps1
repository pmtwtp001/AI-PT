# Netlify deploy pack - includes all assets referenced in index.html
# Run: powershell -ExecutionPolicy Bypass -File scripts/pack-netlify.ps1

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

$deploy = Join-Path $root 'netlify-deploy'
$zip = Join-Path $root 'ai-pt-netlify-deploy.zip'
$dataSrc = Join-Path $root 'data'
$dataDst = Join-Path $deploy 'data'

$coreFiles = @(
    'index.html',
    'line.html',
    '_redirects',
    'script.js',
    'styles.css',
    'translations.js',
    'netlify.toml'
)

# 切勿加入 /* -> index.html 的 _redirects：會讓 /data/*.png 也變成 HTML，整頁圖片空白

$requiredAssets = @(
    'top.png', 'top1.png', 'top2.png', 'top3.png', 'top4.png', 'top5.png',
    'top6.png', 'top7.png', 'top8.png', 'top9.png', 'top10.png', 'top11.png',
    'top12.png', 'top13.png', 'top14.png',
    '1.png', '2.png', '3.png', '4.png',
    'IG6.mp4',
    'line-qrcode.png',
    'AIMakeMoney.png', 'AIMakeMoneyC.png', 'AIMakeMoneyE.png'
)

function Get-DataRefsFromFile([string]$filePath) {
    if (-not (Test-Path $filePath)) { return @() }
    $text = Get-Content -Path $filePath -Raw -Encoding UTF8
    $pattern = 'data/([^\s"''?)]+)'
    $found = @()
    foreach ($m in [regex]::Matches($text, $pattern)) {
        $found += $m.Groups[1].Value
    }
    return $found
}

if (Test-Path $deploy) { Remove-Item $deploy -Recurse -Force }
New-Item -ItemType Directory -Path $dataDst -Force | Out-Null

foreach ($f in $coreFiles) {
    $src = Join-Path $root $f
    if (-not (Test-Path $src)) {
        throw "Missing required file: $f"
    }
    Copy-Item $src $deploy -Force
}

# _redirects 只含 /line、/l 捷徑；勿加入 /* → index.html

$howToPath = Join-Path $deploy 'NETLIFY-UPLOAD-README.txt'
@(
    '=== Avoid Netlify 404 (Page not found) ===',
    '',
    'CORRECT URL (share in LINE):',
    '  https://lambent-pothos-ddb830.netlify.app/line.html',
    '  or https://lambent-pothos-ddb830.netlify.app/line',
    '',
    'CORRECT upload:',
    '  A) Drag folder netlify-deploy into your site Deploys',
    '  B) Or drag ai-pt-netlify-deploy.zip (generated by this script only)',
    '',
    'OPEN ZIP AND CHECK (important):',
    '  index.html must be at ZIP ROOT',
    '  data/top.png must be at ZIP ROOT inside data/',
    '',
    'WRONG (causes 404 on homepage):',
    '  netlify-deploy/index.html  (extra folder layer)',
    '  Right-click zip the parent AI-PT folder',
    '',
    'After deploy, test:',
    '  https://lambent-pothos-ddb830.netlify.app/data/top.png'
) | Set-Content -Path $howToPath -Encoding UTF8

$fromIndex = Get-DataRefsFromFile (Join-Path $root 'index.html')
$fromStyles = Get-DataRefsFromFile (Join-Path $root 'styles.css')
$fromScript = Get-DataRefsFromFile (Join-Path $root 'script.js')

$allRequired = New-Object 'System.Collections.Generic.HashSet[string]' ([StringComparer]::OrdinalIgnoreCase)
foreach ($n in ($requiredAssets + $fromIndex + $fromStyles + $fromScript)) {
    if ($n -match '\?') { $n = $n.Split('?')[0] }
    [void]$allRequired.Add($n)
}

$missing = @()
$copied = 0
foreach ($name in ($allRequired | Sort-Object)) {
    $src = Join-Path $dataSrc $name
    if (-not (Test-Path $src)) {
        $missing += $name
        continue
    }
    Copy-Item $src (Join-Path $dataDst $name) -Force
    $copied++
}

if ($missing.Count -gt 0) {
    Write-Host 'MISSING in data/:'
    $missing | ForEach-Object { Write-Host "  $_" }
    throw 'Pack aborted: assets missing'
}

$stamp = Get-Date -Format 'yyyy-MM-dd HH:mm:ss'
$manifestPath = Join-Path $deploy 'ASSET_MANIFEST.txt'

if (-not (Test-Path (Join-Path $dataDst 'top.png'))) {
    throw 'Pack error: data/top.png missing in deploy folder'
}

$lines = @(
    'Netlify deploy pack',
    "Built: $stamp",
    '',
    'Upload: drag the whole netlify-deploy folder to Netlify Deploys.',
    'Must include index.html AND data/ subfolder together.',
    '',
    'data files:'
)
$lines += ($allRequired | Sort-Object | ForEach-Object { "  data/$_" })
$lines | Set-Content -Path $manifestPath -Encoding UTF8

if (Test-Path $zip) { Remove-Item $zip -Force }
Push-Location $deploy
try {
    Compress-Archive -Path * -DestinationPath $zip -Force -CompressionLevel Optimal
} finally {
    Pop-Location
}

Add-Type -AssemblyName System.IO.Compression.FileSystem
$archive = [IO.Compression.ZipFile]::OpenRead($zip)
try {
    $names = $archive.Entries | ForEach-Object { $_.FullName.Replace('\', '/') }
    $hasRootIndex = $names -contains 'index.html'
    $nestedIndex = $names | Where-Object { $_ -match '^netlify-deploy/' -or $_ -match '^AI-PT/' }
    if (-not $hasRootIndex) {
        throw 'ZIP invalid: index.html is not at ZIP root. Do not zip the parent folder.'
    }
    if ($nestedIndex) {
        throw 'ZIP invalid: extra folder layer inside ZIP (causes Netlify 404). Use script zip only.'
    }
    $hasDataTop = ($names | Where-Object { $_ -eq 'data/top.png' -or $_ -eq 'data\top.png' }).Count -gt 0
    if (-not $hasDataTop) {
        throw 'ZIP invalid: data/top.png missing'
    }
} finally {
    $archive.Dispose()
}

$total = (Get-ChildItem $deploy -Recurse -File | Measure-Object).Count
$dataCount = (Get-ChildItem $dataDst -File | Measure-Object).Count
$mb = [math]::Round((Get-Item $zip).Length / 1MB, 2)

Write-Host ''
Write-Host "OK: $deploy ($total files, data=$dataCount)"
Write-Host "ZIP: $zip ($mb MB)"
Write-Host 'Drag netlify-deploy folder (with data/) to Netlify Deploys.'
